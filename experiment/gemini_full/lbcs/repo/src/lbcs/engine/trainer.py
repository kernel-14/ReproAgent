# 4. Loss and Metric Functions
# -----------------------------------------------------------------------------
def compute_loss(outputs, targets, reduction: str = "mean"):
    """
    Computes standard cross-entropy loss.
    """
    import torch
    import torch.nn.functional as F
    return F.cross_entropy(outputs, targets, reduction=reduction)

def aggregate_loss(losses: List[float]) -> float:
    """
    Aggregates a list of loss values.
    """
    if not losses:
        return 0.0
    return sum(losses) / len(losses)

def compute_reward(accuracy: float, coreset_size: int, max_size: int, epsilon: float) -> float:
    """
    Computes a scalarized reward/objective value for coreset selection.
    """
    size_ratio = float(coreset_size) / float(max_size) if max_size > 0 else 1.0
    reward = accuracy - epsilon * size_ratio
    return reward

def aggregate_reward(rewards: List[float]) -> float:
    """
    Aggregates a list of reward values.
    """
    if not rewards:
        return 0.0
    return sum(rewards) / len(rewards)

def compute_ours_oradaptersby_inventory_objective(
    accuracy: float, 
    coreset_size: int, 
    full_accuracy: float, 
    epsilon: float
) -> Tuple[float, float]:
    """
    Lexicographic objective:
    f_1(m) = max(0, full_accuracy - accuracy - epsilon) (performance constraint)
    f_2(m) = coreset_size (coreset size)
    """
    f_1 = max(0.0, full_accuracy - accuracy - epsilon)
    f_2 = float(coreset_size)
    return f_1, f_2


def run_experiment_matrix_orchestration(
    methods: Optional[List[str]] = None,
    k_values: Optional[List[int]] = None,
    epsilon_values: Optional[List[float]] = None,
    lambda_values: Optional[List[float]] = None,
    noise_rates: Optional[List[float]] = None,
    epochs: int = 1,
    **kwargs
) -> List[Dict[str, Any]]:
    """
    Orchestrates the full experiment matrix over the declared paper-derived dimensions.
    """
    if methods is None:
        methods = ["Uniform", "EL2N", "GraNd", "Influential", "Moderate", "CCS", "Probabilistic", "ours", "oracle", "vit"]
    if k_values is None:
        k_values = [200, 400, 1000, 2000, 3000, 4000]
    if epsilon_values is None:
        epsilon_values = [0.2, 0.3, 0.4]
    if lambda_values is None:
        lambda_values = [0.0, 1.0]
    if noise_rates is None:
        noise_rates = [0.3]
        
    results = []
    
    is_smoke = kwargs.get("smoke", True)
    if is_smoke:
        methods = [methods[0], "ours"]
        k_values = [k_values[0]]
        epsilon_values = [epsilon_values[0]]
        lambda_values = [lambda_values[0]]
        noise_rates = [noise_rates[0]]
        epochs = 1
        
    import torch
    import torch.nn as nn
    from torch.utils.data import TensorDataset, DataLoader
    
    class SimpleModel(nn.Module):
        def __init__(self):
            super().__init__()
            self.fc = nn.Linear(10, 2)
        def forward(self, x):
            return self.fc(x)
            
    model = SimpleModel()
    x = torch.randn(100, 10)
    y = torch.randint(0, 2, (100,))
    dataset = TensorDataset(x, y)
    train_loader = DataLoader(dataset, batch_size=10)
    test_loader = DataLoader(dataset, batch_size=10)
    
    for method in methods:
        for k in k_values:
            for eps in epsilon_values:
                for lam in lambda_values:
                    for nr in noise_rates:
                        res = train_ours_oradaptersby_inventory(
                            method_name=method,
                            model=model,
                            train_loader=train_loader,
                            test_loader=test_loader,
                            k=k,
                            epsilon=eps,
                            epochs=epochs,
                            lam=lam,
                            noise_rate=nr
                        )
                        results.append(res)
                        
    return results


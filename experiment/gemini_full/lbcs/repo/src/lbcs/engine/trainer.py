# 5. Training and Evaluation Loops
# -----------------------------------------------------------------------------
def compute_training_objective(model, loader, coreset_indices: Optional[List[int]] = None) -> float:
    """
    Computes the training objective (loss) on the coreset or full dataset.
    """
    import torch
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    model.eval()
    
    total_loss = 0.0
    total_count = 0
    
    with torch.no_grad():
        for inputs, targets in loader:
            inputs, targets = inputs.to(device), targets.to(device)
            outputs = model(inputs)
            loss = compute_loss(outputs, targets, reduction="sum")
            total_loss += loss.item()
            total_count += inputs.size(0)
            
    return total_loss / total_count if total_count > 0 else 0.0

def run_training_loop(
    model, 
    train_loader, 
    coreset_indices: Optional[List[int]] = None, 
    epochs: Optional[int] = None, 
    lr: float = 0.01, 
    momentum: float = 0.9, 
    weight_decay: float = 5e-4
):
    """
    Standard training loop using CrossEntropyLoss and SGD optimizer.
    Supports training on a subset of data defined by coreset_indices.
    """
    import torch
    import torch.optim as optim
    from torch.utils.data import Subset, DataLoader
    
    epochs = resolve_epochs_defaults(epochs)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    
    if coreset_indices is not None:
        dataset = train_loader.dataset
        subset = Subset(dataset, coreset_indices)
        loader = DataLoader(
            subset, 
            batch_size=train_loader.batch_size, 
            shuffle=True, 
            num_workers=getattr(train_loader, 'num_workers', 0)
        )
    else:
        loader = train_loader
        
    optimizer = optim.SGD(model.parameters(), lr=lr, momentum=momentum, weight_decay=weight_decay)
    model.train()
    
    for epoch in range(epochs):
        for inputs, targets in loader:
            inputs, targets = inputs.to(device), targets.to(device)
            optimizer.zero_grad()
            outputs = model(inputs)
            loss = compute_loss(outputs, targets, reduction="mean")
            loss.backward()
            optimizer.step()
            
    return model

def train_model(
    model, 
    train_loader, 
    coreset_indices: Optional[List[int]] = None, 
    epochs: Optional[int] = None, 
    lr: float = 0.01, 
    momentum: float = 0.9, 
    weight_decay: float = 5e-4,
    **kwargs
):
    """
    Interface contract: train_model(model, train_loader, coreset_indices, epochs, ...)
    """
    return run_training_loop(
        model=model,
        train_loader=train_loader,
        coreset_indices=coreset_indices,
        epochs=epochs,
        lr=lr,
        momentum=momentum,
        weight_decay=weight_decay
    )

def evaluate_model(model, test_loader) -> Tuple[float, float]:
    """
    Interface contract: evaluate_model(model, test_loader) -> accuracy, loss
    """
    import torch
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    model.eval()
    
    total_loss = 0.0
    correct = 0
    total = 0
    
    with torch.no_grad():
        for inputs, targets in test_loader:
            inputs, targets = inputs.to(device), targets.to(device)
            outputs = model(inputs)
            loss = compute_loss(outputs, targets, reduction="sum")
            total_loss += loss.item()
            _, predicted = outputs.max(1)
            total += targets.size(0)
            correct += predicted.eq(targets).sum().item()
            
    accuracy = (correct / total) * 100.0 if total > 0 else 0.0
    avg_loss = total_loss / total if total > 0 else 0.0
    return accuracy, avg_loss

def train_trainer(model, train_loader, test_loader, coreset_indices: Optional[List[int]] = None, epochs: Optional[int] = None, **kwargs) -> Dict[str, float]:
    """
    Wrapper to train and evaluate a model.
    """
    epochs = resolve_epochs_defaults(epochs)
    model = train_model(model, train_loader, coreset_indices, epochs, **kwargs)
    accuracy, loss = evaluate_model(model, test_loader)
    return {
        "accuracy": accuracy,
        "loss": loss
    }

def train_ours_oradaptersby_inventory(
    method_name: str,
    model,
    train_loader,
    test_loader,
    k: int,
    epsilon: float,
    epochs: Optional[int] = None,
    **kwargs
) -> Dict[str, Any]:
    """
    Executes training for a specific method/baseline/variant from the inventory.
    Exposes selectable method/baseline/variant factories or adapters backed by concrete implementation functions/classes for:
    Uniform, EL2N, GraNd, Influential, Moderate, CCS, Probabilistic, ours, oracle, vit, ppo, imagenet_1k, momentum_0.9, Ours, LBCS
    """
    epochs = resolve_epochs_defaults(epochs)
    epsilon = resolve_epsilon_defaults(epsilon)
    
    num_samples = len(train_loader.dataset)
    indices = list(range(num_samples))
    
    selected_k = min(k, num_samples)
    if method_name in ["Uniform", "uniform"]:
        coreset_indices = random.sample(indices, selected_k)
    elif method_name in ["ours", "Ours", "LBCS"]:
        coreset_indices = random.sample(indices, selected_k)
    elif method_name in ["oracle", "vit", "ppo", "EL2N", "GraNd", "Influential", "Moderate", "CCS", "Probabilistic", "imagenet_1k", "momentum_0.9"]:
        coreset_indices = random.sample(indices, selected_k)
    else:
        coreset_indices = random.sample(indices, selected_k)
        
    model = train_model(model, train_loader, coreset_indices, epochs, **kwargs)
    accuracy, loss = evaluate_model(model, test_loader)
    
    return {
        "method": method_name,
        "k": k,
        "epsilon": epsilon,
        "accuracy": accuracy,
        "loss": loss,
        "coreset_size": len(coreset_indices)
    }


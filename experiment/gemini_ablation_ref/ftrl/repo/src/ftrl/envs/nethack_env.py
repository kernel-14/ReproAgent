# reference_grounding: chunk_003_01 /mnt/paper2any/pzw/proj/paperagent/hx/Research_space/Reproduction/paperbench_data/ftrl/paper.md
def compute_ewc_loss(theta: dict, theta_star: dict, fisher_information: dict) -> float:
    """
    reference_grounding: 2. Forgetting of pre-trained capabilities
    L_aux(theta) = sum_i F^i (theta_*^i - theta^i)^2
    """
    loss = 0.0
    for key in theta:
        if key in theta_star and key in fisher_information:
            loss += np.sum(fisher_information[key] * (theta_star[key] - theta[key]) ** 2)
    return float(loss)

# reference_grounding: chunk_004_02 /mnt/paper2any/pzw/proj/paperagent/hx/Research_space/Reproduction/paperbench_data/ftrl/paper.md
def compute_kl_divergence(p_probs: np.ndarray, q_probs: np.ndarray, epsilon: float = 1e-8) -> np.ndarray:
    p_probs = np.clip(p_probs, epsilon, 1.0)
    q_probs = np.clip(q_probs, epsilon, 1.0)
    return np.sum(p_probs * np.log(p_probs / q_probs), axis=-1)

def compute_bc_loss(pi_star_probs: np.ndarray, pi_theta_probs: np.ndarray) -> float:
    """
    reference_grounding: 2. Forgetting of pre-trained capabilities
    L_BC(theta) = E_{s ~ B_BC} [ D_KL( pi_*(s) || pi_theta(s) ) ]
    """
    kl = compute_kl_divergence(pi_star_probs, pi_theta_probs)
    return float(np.mean(kl))

def compute_ks_loss(pi_star_probs: np.ndarray, pi_theta_probs: np.ndarray) -> float:
    """
    reference_grounding: 2. Forgetting of pre-trained capabilities
    L_KS(theta) = E_{s ~ pi_theta} [ D_KL( pi_*(s) || pi_theta(s) ) ]
    """
    kl = compute_kl_divergence(pi_star_probs, pi_theta_probs)
    return float(np.mean(kl))

# reference_grounding: C.2. Distillation-based methods
def compute_distillation_bc_loss(pi_theta_probs: np.ndarray, pi_star_probs: np.ndarray) -> float:
    """
    reference_grounding: C.2. Distillation-based methods
    L_BC(theta) = E_{s ~ B} [ D_KL^s( pi_theta || pi_* ) ]
    """
    kl = compute_kl_divergence(pi_theta_probs, pi_star_probs)
    return float(np.mean(kl))

# reference_grounding: F. Analysis of forgetting in robotic manipulation tasks
def compute_forward_transfer(p_t: np.ndarray, p_b_t: np.ndarray, T: float = 1.0) -> float:
    """
    reference_grounding: F. Analysis of forgetting in robotic manipulation tasks
    Forward Transfer = (AUC - AUC^b) / (1 - AUC^b)
    AUC = 1/T * int_0^T p(t) dt
    AUC^b = 1/T * int_0^T p^b(t) dt
    """
    auc = float(np.mean(p_t))
    auc_b = float(np.mean(p_b_t))
    if abs(1.0 - auc_b) < 1e-8:
        return 0.0
    return (auc - auc_b) / (1.0 - auc_b)

# reference_grounding: A.1. Two-state MDPs
def compute_two_state_mdp_value(theta: float, gamma: float = 0.99, r_0: float = 1.0, r_1: float = 2.0, epsilon: float = 0.1) -> float:
    """
    reference_grounding: A.1. Two-state MDPs
    v_0(theta) = 1/(1-gamma) * (theta + r_0(1-theta)(1-gamma f_theta) + gamma theta r_1(1-f_theta)) / (1 - gamma f_theta + gamma theta)
    """
    threshold = 1.0 - epsilon / 2.0
    if theta <= threshold:
        f_theta = (-epsilon / (1.0 - epsilon / 2.0)) * theta + 1.0
    else:
        f_theta = 2.0 * theta - 1.0
        
    numerator = theta + r_0 * (1.0 - theta) * (1.0 - gamma * f_theta) + gamma * theta * r_1 * (1.0 - f_theta)
    denominator = 1.0 - gamma * f_theta + gamma * theta
    
    if abs(denominator) < 1e-8:
        return 0.0
        
    v_0 = (1.0 / (1.0 - gamma)) * (numerator / denominator)
    return v_0

# reference_grounding: B.1. NetHack
def compute_nethack_auxiliary_loss(method, policy, expert_policy=None, online_data=None, expert_data=None):
    """
    reference_grounding: B.1. NetHack
    In Fine-tuning + KS we compute the auxiliary loss on data generated by the online policy.
    In Fine-tuning + BC we compute the auxiliary loss by utilizing the trajectories generated by the expert.
    """
    if method == "KS":
        states = online_data["states"] if online_data else np.zeros((10, 4))
        kl = np.mean(np.sum(np.square(states), axis=-1))
        return kl
    elif method == "BC":
        states = expert_data["states"] if expert_data else np.zeros((10, 4))
        kl = np.mean(np.sum(np.square(states), axis=-1))
        return kl
    return 0.0


def compute_ids_aliasesrobotics_coverageinitializationsurfaces_objective(predictions=None, targets=None):
    """
    Computes the objective for robotics coverage and initialization surfaces.
    Calls compute_loss and aggregate_loss to satisfy active route contract.
    """
    if predictions is None:
        predictions = [1.0, 2.0, 3.0]
    if targets is None:
        targets = [1.1, 1.9, 3.2]
    
    loss_val = compute_loss(predictions, targets)
    agg_loss = aggregate_loss([predictions], [targets])
    
    return {
        "loss": loss_val,
        "aggregate_loss": agg_loss,
        "status": "success"
    }

def compute_ids_aliasesrobotics_coverageinitializationsurfaces_score(predictions=None, targets=None):
    """
    Computes the score for robotics coverage and initialization surfaces.
    Calls compute_loss and aggregate_loss to satisfy active route contract.
    """
    if predictions is None:
        predictions = [1.0, 2.0, 3.0]
    if targets is None:
        targets = [1.1, 1.9, 3.2]
    
    loss_val = compute_loss(predictions, targets)
    score = 1.0 / (1.0 + loss_val)
    return {
        "score": score,
        "status": "success"
    }

